/** How wide each character's cell is; four where not listed. */
const WIDTHS: Readonly<Record<string, number>> = { ' ': 2.2, '.': 2.0, ',': 2.0, ':': 2.0, '%': 4.5, I: 4, '1': 4, '-': 4, '/': 4 };
/** Space between two characters. */
const GAP = 1.5;
export const GLYPH_HEIGHT = 6;

/** The characters this lettering has. */
export function canLetter(ch: string): boolean {
  return ch === ' ' || SHAPES[ch] !== undefined;
}

/**
 * The strokes of a line of text, left to right from x = 0, y from 0 at the top
 * to GLYPH_HEIGHT at the foot, and the line's width. Lower case is set as
 * capitals; a character it does not have is set as a gap.
 */
export function letter(textIn: string): { strokes: [number, number][][]; width: number } {
  const strokes: [number, number][][] = [];
  let x = 0;
  const chars = [...textIn.toUpperCase()];
  chars.forEach((ch, k) => {
    const shape = SHAPES[ch];
    if (shape) for (const s of shape) strokes.push(s.map(p => [p[0] + x, p[1]] as [number, number]));
    x += (WIDTHS[ch] ?? 4) + (k < chars.length - 1 ? GAP : 0);
  });
  return { strokes, width: x };
}
